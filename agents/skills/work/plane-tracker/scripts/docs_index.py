#!/usr/bin/env python3
"""Genera docs/INDEX.md a partir del front-matter de docs/{defects,rfcs,decisions}/NNNN-*.md (o de NNNN-*/README.md
cuando el ítem tiene varios documentos).

Uso: docs_index.py [--check]   (--check no escribe: sale con 1 si INDEX.md no está al día)."""
import os
import re
import sys

DOCS = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs")
INDEX = os.path.join(DOCS, "INDEX.md")
REQUIRED = ("id", "title", "status", "created", "summary")
# kind -> (section title, valid statuses)
KINDS = {
    "decisions": ("Decisions", ("accepted", "superseded", "draft")),
    "rfcs": ("Requests for Comments (RFC)", ("draft", "proposed", "accepted", "implemented", "rejected", "superseded", "borrador")),
}
FILE_RE = re.compile(r"^(\d{4})-[a-z0-9-]+(\.md)?$")  # standalone file or item folder
HEADER = """# Development Documentation Index

> Auto-generated by `scripts/docs_index.py`; do not edit by hand. An RFC only exists in code once its status is
> `implemented`. Conventions: [README](./README.md).
"""


def parse_front_matter(text):
    """Devuelve {clave: valor} del bloque `---` inicial (YAML plano `clave: valor`, con comillas opcionales)."""
    match = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not match:
        return {}
    data = {}
    for line in match.group(1).splitlines():
        key, sep, value = line.partition(":")
        if sep:
            value = value.strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1]
            data[key.strip()] = value
    return data


def entry_file(folder, name):
    """Archivo con el front-matter de un ítem: el propio .md o el README.md de su carpeta."""
    path = os.path.join(folder, name)
    return os.path.join(path, "README.md") if os.path.isdir(path) else path


def collect(docs_dir=DOCS):
    """[(carpeta, nombre, front_matter)] ordenado por ID; el nombre es el del archivo o el de la carpeta del ítem."""
    items = []
    for kind in KINDS:
        folder = os.path.join(docs_dir, kind)
        if not os.path.isdir(folder):
            continue
        for name in sorted(os.listdir(folder)):
            if os.path.isdir(os.path.join(folder, name)) or name.endswith(".md"):
                entry = entry_file(folder, name)
                meta = {}
                if os.path.exists(entry):
                    with open(entry, encoding="utf-8") as handle:
                        meta = parse_front_matter(handle.read())
                items.append((kind, name, meta))
    return sorted(items, key=lambda item: item[1][:4])


def render(items, docs_dir=DOCS):
    lines = [HEADER]
    for kind, (title, _states) in KINDS.items():
        rows = [item for item in items if item[0] == kind]
        lines.append(f"\n## {title}\n")
        if not rows:
            lines.append("_No documents._")
            continue
        lines.append("| ID | Title | Status | Summary |\n| :--- | :--- | :--- | :--- |")
        for _kind, name, meta in rows:
            summary = meta.get("summary", "").replace("|", "\\|")
            target = f"{kind}/{name}" + ("/README.md" if os.path.isdir(os.path.join(docs_dir, kind, name)) else "")
            lines.append(f"| {name[:4]} | [{meta.get('title', name)}]({target}) | {meta.get('status', '?')} | {summary} |")
    return "\n".join(lines) + "\n"


def main(argv):
    text = render(collect())
    if "--check" in argv:
        current = open(INDEX, encoding="utf-8").read() if os.path.exists(INDEX) else ""
        if current != text:
            sys.stderr.write("docs/INDEX.md no está al día: ejecuta scripts/docs_index.py\n")
            return 1
        return 0
    with open(INDEX, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"docs/INDEX.md: {len(collect())} documentos")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
